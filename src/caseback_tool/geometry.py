"""OpenSCAD source generation and export helpers."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
import math
import shutil
import subprocess


@dataclass(frozen=True)
class DiskSpec:
    notch_circle_diameter: float
    notch_count: int
    notch_depth: float
    notch_length: float
    notch_width: float
    disk_diameter: float | None = None
    body_thickness: float = 5.0
    drive_af: float = 12.0
    drive_height: float = 7.0
    insert_diameter: float = 5.6
    insert_depth: float = 5.5
    facets: int = 128

    @property
    def resolved_disk_diameter(self) -> float:
        if self.disk_diameter is not None:
            return self.disk_diameter
        return self.notch_circle_diameter + self.notch_length + 2.0

    def validate(self) -> None:
        positive = {
            "notch circle diameter": self.notch_circle_diameter,
            "notch depth": self.notch_depth,
            "notch length": self.notch_length,
            "notch width": self.notch_width,
            "disk diameter": self.resolved_disk_diameter,
            "body thickness": self.body_thickness,
            "drive AF": self.drive_af,
            "drive height": self.drive_height,
            "insert diameter": self.insert_diameter,
            "insert depth": self.insert_depth,
        }
        for name, value in positive.items():
            if not math.isfinite(value) or value <= 0:
                raise ValueError(f"{name} must be a positive finite number")
        if self.notch_count < 2:
            raise ValueError("notch count must be at least 2")
        if self.facets < 24:
            raise ValueError("facets must be at least 24")
        minimum_disk = self.notch_circle_diameter + self.notch_length
        if self.resolved_disk_diameter < minimum_disk:
            raise ValueError(
                f"disk diameter must be at least {minimum_disk:.3f} mm to cover the teeth"
            )
        circumference_per_notch = math.pi * self.notch_circle_diameter / self.notch_count
        if self.notch_width >= circumference_per_notch:
            raise ValueError("notch width is too large for the selected circle and count")
        if self.insert_depth >= self.drive_height + self.body_thickness - 1.0:
            raise ValueError("insert depth leaves too little material under the insert")
        if self.insert_diameter >= self.drive_af - 2.0:
            raise ValueError("insert diameter leaves too little wall in the hex drive")


@dataclass(frozen=True)
class HandleSpec:
    handle_length: float = 130.0
    handle_width: float = 24.0
    handle_thickness: float = 12.0
    drive_af: float = 12.0
    drive_height: float = 7.0
    fit_clearance: float = 0.25
    screw_clearance: float = 4.5
    screw_head_diameter: float = 8.0
    screw_head_depth: float = 3.4
    facets: int = 128

    def validate(self) -> None:
        values = {
            "handle length": self.handle_length,
            "handle width": self.handle_width,
            "handle thickness": self.handle_thickness,
            "drive AF": self.drive_af,
            "drive height": self.drive_height,
            "fit clearance": self.fit_clearance,
            "screw clearance": self.screw_clearance,
            "screw head diameter": self.screw_head_diameter,
            "screw head depth": self.screw_head_depth,
        }
        for name, value in values.items():
            if not math.isfinite(value) or value <= 0:
                raise ValueError(f"{name} must be a positive finite number")
        if self.handle_length <= self.handle_width:
            raise ValueError("handle length must be greater than handle width")
        if self.handle_width < self.drive_af + 6.0:
            raise ValueError("handle width must be at least drive AF + 6 mm")
        if self.drive_height >= self.handle_thickness - 1.5:
            raise ValueError("drive height leaves too little material at the top of the handle")
        if self.screw_head_depth >= self.handle_thickness - self.drive_height:
            raise ValueError("screw head depth intersects the hex socket")
        if self.facets < 24:
            raise ValueError("facets must be at least 24")


def _n(value: float) -> str:
    return f"{value:.6f}".rstrip("0").rstrip(".")


def disk_scad(spec: DiskSpec) -> str:
    spec.validate()
    d = spec.resolved_disk_diameter
    tooth_radius = spec.notch_circle_diameter / 2.0
    body_z = spec.notch_depth
    connector_z = body_z + spec.body_thickness
    hex_r = spec.drive_af / math.sqrt(3.0)
    return f'''// Generated by watch-caseback-tool. Units: millimetres.
// notch_circle_diameter is the pitch circle through the tooth centres.
$fn = {spec.facets};

module caseback_disk() {{
    difference() {{
        union() {{
            // Male teeth: length is radial, width tangential, depth axial.
            for (a = [0 : 360/{spec.notch_count} : 360-360/{spec.notch_count}]) {{
                rotate([0, 0, a])
                    translate([{_n(tooth_radius)}, 0, {_n((spec.notch_depth + 0.08) / 2.0)}])
                        cube([{_n(spec.notch_length)}, {_n(spec.notch_width)}, {_n(spec.notch_depth + 0.08)}], center=true);
            }}

            // Main disk body.
            translate([0, 0, {_n(body_z)}])
                cylinder(d={_n(d)}, h={_n(spec.body_thickness)});

            // Standard 12 mm AF male hex drive, with a lead-in chamfer.
            translate([0, 0, {_n(connector_z)}]) {{
                cylinder(r={_n(hex_r)}, h={_n(spec.drive_height - 0.8)}, $fn=6);
                translate([0, 0, {_n(spec.drive_height - 0.8)}])
                    cylinder(r1={_n(hex_r)}, r2={_n(hex_r - 0.5)}, h=0.8, $fn=6);
            }}
        }}

        // Pocket for an M4 heat-set insert; install from the top of the hex.
        translate([0, 0, {_n(connector_z + spec.drive_height - spec.insert_depth)}])
            cylinder(d={_n(spec.insert_diameter)}, h={_n(spec.insert_depth + 0.2)});
        translate([0, 0, {_n(connector_z + spec.drive_height - 0.7)}])
            cylinder(d1={_n(spec.insert_diameter)}, d2={_n(spec.insert_diameter + 1.0)}, h=0.8);
    }}
}}

caseback_disk();
'''


def handle_scad(spec: HandleSpec) -> str:
    spec.validate()
    end_offset = (spec.handle_length - spec.handle_width) / 2.0
    socket_af = spec.drive_af + 2.0 * spec.fit_clearance
    socket_r = socket_af / math.sqrt(3.0)
    return f'''// Generated by watch-caseback-tool. Units: millimetres.
$fn = {spec.facets};

module handle_blank() {{
    linear_extrude(height={_n(spec.handle_thickness)})
        hull() {{
            translate([{_n(-end_offset)}, 0]) circle(d={_n(spec.handle_width)});
            translate([{_n(end_offset)}, 0]) circle(d={_n(spec.handle_width)});
        }}
}}

module caseback_handle() {{
    difference() {{
        handle_blank();

        // Female hex socket. Hex geometry transmits torque in both directions.
        translate([0, 0, -0.1])
            cylinder(r={_n(socket_r)}, h={_n(spec.drive_height + 0.2)}, $fn=6);
        // Lead-in chamfer at the underside of the socket.
        translate([0, 0, -0.1])
            cylinder(r1={_n(socket_r + 0.55)}, r2={_n(socket_r)}, h=0.9, $fn=6);

        // M4 retaining screw and recessed head.
        translate([0, 0, -0.1])
            cylinder(d={_n(spec.screw_clearance)}, h={_n(spec.handle_thickness + 0.2)});
        translate([0, 0, {_n(spec.handle_thickness - spec.screw_head_depth)}])
            cylinder(d={_n(spec.screw_head_diameter)}, h={_n(spec.screw_head_depth + 0.1)});

        // Shallow finger grooves on the upper face.
        for (x = [{_n(-end_offset + 9)} : 11 : {_n(end_offset - 9)}]) {{
            if (abs(x) > 15)
                translate([x, 0, {_n(spec.handle_thickness - 0.65)}])
                    rotate([90, 0, 0]) cylinder(d=2.2, h={_n(spec.handle_width + 1)}, center=true, $fn=32);
        }}
    }}
}}

caseback_handle();
'''


def write_scad(path: Path, source: str) -> Path:
    path = path.resolve()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source, encoding="utf-8")
    return path


def export_stl(scad_path: Path, stl_path: Path, openscad: str | None = None) -> Path:
    executable = openscad or shutil.which("openscad")
    if not executable:
        raise RuntimeError("OpenSCAD was not found on PATH; install it or use --scad-only")
    stl_path = stl_path.resolve()
    stl_path.parent.mkdir(parents=True, exist_ok=True)
    command = [
        executable,
        "--hardwarnings",
        "--check-parameters=true",
        "--export-format=binstl",
        "-o",
        str(stl_path),
        str(scad_path.resolve()),
    ]
    result = subprocess.run(command, text=True, capture_output=True)
    if result.returncode != 0:
        details = (result.stderr or result.stdout).strip()
        raise RuntimeError(f"OpenSCAD export failed: {details}")
    return stl_path


def render_stl_png(
    stl_path: Path,
    png_path: Path,
    layout: str,
    part_height: float,
    image_size: tuple[int, int] = (1200, 800),
    blender: str | None = None,
) -> Path:
    executable = blender or shutil.which("blender")
    if not executable:
        raise RuntimeError("Blender was not found on PATH; STL files were still generated")
    png_path = png_path.resolve()
    png_path.parent.mkdir(parents=True, exist_ok=True)
    script_path = png_path.with_suffix(".blender.py")
    if layout not in {"disk", "handle"}:
        raise ValueError("render layout must be 'disk' or 'handle'")
    if layout == "disk":
        positions = [(-21.0, 0.0, 0.0), (21.0, 0.0, part_height)]
        rotations = [(0.0, 0.0, 0.0), (math.pi, 0.0, math.radians(30.0))]
        camera_location = (0.0, -105.0, 76.0)
        camera_target = (0.0, 0.0, 5.0)
        ortho_scale = 62.0
    else:
        positions = [(0.0, 16.0, 0.0), (0.0, -17.0, part_height)]
        rotations = [(0.0, 0.0, 0.0), (math.pi, 0.0, 0.0)]
        camera_location = (0.0, -185.0, 135.0)
        camera_target = (0.0, 0.0, 4.0)
        ortho_scale = 86.0
    script = f'''import bpy
import math
from mathutils import Vector

bpy.ops.object.select_all(action="SELECT")
bpy.ops.object.delete(use_global=False)

def material(name, rgba, metallic=0.0, roughness=0.34):
    mat = bpy.data.materials.new(name)
    mat.diffuse_color = rgba
    mat.use_nodes = True
    node = mat.node_tree.nodes.get("Principled BSDF")
    node.inputs["Base Color"].default_value = rgba
    node.inputs["Metallic"].default_value = metallic
    node.inputs["Roughness"].default_value = roughness
    return mat

orange = material("Tool orange", (0.95, 0.31, 0.055, 1.0), 0.05, 0.29)
blue = material("Underside blue", (0.035, 0.27, 0.62, 1.0), 0.08, 0.3)

def load_part(location, rotation, mat):
    bpy.ops.wm.stl_import(filepath={str(stl_path.resolve())!r})
    obj = bpy.context.active_object
    obj.location = location
    obj.rotation_euler = rotation
    obj.data.materials.append(mat)
    bevel = obj.modifiers.new("Render edge highlights", "BEVEL")
    bevel.width = 0.12
    bevel.segments = 2
    return obj

load_part({positions[0]!r}, {rotations[0]!r}, orange)
load_part({positions[1]!r}, {rotations[1]!r}, blue)

# Neutral floor for readable contact shadows.
bpy.ops.mesh.primitive_plane_add(size=320, location=(0, 0, -0.3))
floor = bpy.context.active_object
floor.data.materials.append(material("Floor", (0.81, 0.84, 0.87, 1.0), 0.0, 0.72))

world = bpy.context.scene.world
world.color = (0.055, 0.07, 0.09)
world.use_nodes = True
world.node_tree.nodes["Background"].inputs["Color"].default_value = (0.035, 0.05, 0.07, 1.0)
world.node_tree.nodes["Background"].inputs["Strength"].default_value = 0.32

def area_light(name, location, energy, size, color):
    data = bpy.data.lights.new(name, type="AREA")
    data.energy = energy
    data.shape = "DISK"
    data.size = size
    data.color = color
    obj = bpy.data.objects.new(name, data)
    bpy.context.collection.objects.link(obj)
    obj.location = location
    direction = Vector((0, 0, 4)) - obj.location
    obj.rotation_euler = direction.to_track_quat("-Z", "Y").to_euler()

area_light("Key", (-55, -70, 110), 1050, 65, (1.0, 0.88, 0.76))
area_light("Fill", (75, -15, 70), 720, 55, (0.68, 0.82, 1.0))
area_light("Rim", (0, 80, 95), 900, 45, (1.0, 0.42, 0.18))

camera_data = bpy.data.cameras.new("Camera")
camera = bpy.data.objects.new("Camera", camera_data)
bpy.context.collection.objects.link(camera)
camera.location = {camera_location!r}
direction = Vector({camera_target!r}) - camera.location
camera.rotation_euler = direction.to_track_quat("-Z", "Y").to_euler()
camera.data.type = "ORTHO"
camera.data.ortho_scale = {ortho_scale}
bpy.context.scene.camera = camera

scene = bpy.context.scene
scene.render.engine = "BLENDER_WORKBENCH"
scene.display.shading.light = "STUDIO"
scene.display.shading.color_type = "MATERIAL"
scene.display.shading.show_shadows = True
scene.display.shading.show_cavity = True
scene.display.shading.cavity_type = "WORLD"
scene.display.shading.curvature_ridge_factor = 1.7
scene.display.shading.curvature_valley_factor = 1.35
scene.display.shading.show_specular_highlight = True
scene.display.shading.background_type = "WORLD"
scene.render.resolution_x = {image_size[0]}
scene.render.resolution_y = {image_size[1]}
scene.render.resolution_percentage = 100
scene.render.image_settings.file_format = "PNG"
scene.render.image_settings.color_mode = "RGBA"
scene.render.film_transparent = False
scene.render.filepath = {str(png_path)!r}
scene.render.image_settings.color_depth = "8"
scene.view_settings.look = "AgX - Medium High Contrast"
bpy.ops.render.render(write_still=True)
'''
    script_path.write_text(script, encoding="utf-8")
    command = [executable, "--background", "--factory-startup", "--python", str(script_path)]
    result = subprocess.run(command, text=True, capture_output=True)
    if result.returncode != 0 or not png_path.exists() or png_path.stat().st_size == 0:
        details = (result.stderr or result.stdout).strip()
        raise RuntimeError(f"Blender render failed: {details}")
    script_path.unlink(missing_ok=True)
    return png_path


def png_to_jpg(png_path: Path, jpg_path: Path, ffmpeg: str | None = None) -> Path:
    executable = ffmpeg or shutil.which("ffmpeg")
    if not executable:
        raise RuntimeError("ffmpeg was not found on PATH; PNG render was retained")
    jpg_path = jpg_path.resolve()
    command = [
        executable,
        "-hide_banner",
        "-loglevel",
        "error",
        "-y",
        "-i",
        str(png_path.resolve()),
        "-q:v",
        "2",
        str(jpg_path),
    ]
    result = subprocess.run(command, text=True, capture_output=True)
    if result.returncode != 0:
        raise RuntimeError(f"JPEG conversion failed: {result.stderr.strip()}")
    return jpg_path
